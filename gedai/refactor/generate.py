"""Generate ``actions.c``/``actions.h`` from the oracle.

This module is the safety net: it produces a complete, compiling
implementation of the new registry without consulting a model.  If the
model stage never runs, or runs badly, the tree still builds.

Output shape
------------

``actions.h`` declares, for every action:

* ``extern GschemAction *action_<cid>;``
* ``void action_callback_<cid> (GschemAction *, GschemToplevel *);``

``actions.c`` contains, in order:

1. the definition of every ``action_<cid>`` global, initialised to NULL;
2. one ``GschemActionSpec`` row per action, in oracle order;
3. ``gschem_register_all_actions()``, which walks the table;
4. the 135 callback definitions, bodies copied verbatim from the oracle.

The metadata strings use ``N_()`` because a static initialiser cannot call
``gettext``; :func:`gschem_action_register` applies ``_()`` at registration
time.
"""


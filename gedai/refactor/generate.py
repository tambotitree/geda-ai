C_HEADER_NOTE = """
/*! \\file actions.c
 *
 * \\brief Action registry definitions.
 *
 * Every action is described by one row of the ::action_specs table and one
 * callback function.  There is no preprocessor fan-out and no generated
 * intermediate file: this file is compiled directly.
 *
 * The table is generated from the historical DEFINE_ACTION definitions by
 * ``python3 -m gedai.refactor gen``; see gschem/src/README.md.  Edit the
 * table rather than re-running the generator once the refactor is closed.
 */

#include "config.h"

#include <glib/gi18n.h>

#include "gschem.h"
#include "gschem_action.h"
#include "actions.h"
"""

H_HEADER_NOTE = """
/*! \\file actions.h
 *
 * \\brief Declarations for gschem's actions.
 *
 * Generated by ``python3 -m gedai.refactor gen``; see gschem/src/README.md.
 *
 * Source files that need to reference an individual action (for example to
 * change its sensitivity) include this file.  Callbacks are declared here
 * too, so the registry table in actions.c is checked by the compiler: a
 * misspelt callback name is a build error, not a silently dead menu item.
 *
 * \\note These are the actions implemented in C.  Actions defined by the
 *       user, or by a Scheme module such as gschem/scheme/pcb.scm, are
 *       registered at load time through gschem_action_register() and have no
 *       entry here; they are not built-in and must not be added to the table.
 */

#ifndef GSCHEM_ACTIONS_H
#define GSCHEM_ACTIONS_H

#include <glib.h>

#include "gschem_action.h"

G_BEGIN_DECLS
"""


def fix_void_argument_calls(body):
    """Rewrite ``call (void)`` to ``call ()`` inside a callback body.

    Under the old macro the body was pasted into a context where a bare
    ``void`` was merely an unhelpful type name.  As a real function body it
    is a hard error, so this narrow, mechanical rewrite is applied and every
    rewrite is reported by the caller rather than applied silently.
    """
    return _VOID_CALL_RE.sub(r"\1 ()", body)


_VOID_CALL_RE = re.compile(r"(\b[A-Za-z_][A-Za-z0-9_]*)\s*\(\s*void\s*\)")


def rewrite_body(body):
    """Return (fixed_body, [descriptions of changes applied])."""
    fixed = fix_void_argument_calls(body)
    changes = []
    if fixed != body:
        changes.append("rewrote 'call (void)' as 'call ()'")
    return fixed, changes


def _c_expr(raw):
    """Re-emit an oracle argument as a C expression.

    The oracle text is already valid C, so it is passed through unchanged
    except that ``_()`` becomes ``N_()``: a static initialiser cannot call
    ``gettext()``, so translation happens in ``gschem_action_register()``
    instead.  Passing the raw text through also preserves adjacent string
    concatenation, which several tooltips rely on.
    """
    expr = raw.strip()
    if expr.startswith("_("):
        return "N" + expr
    return expr


def _spec_row(entry):
    """Render one ::GschemActionSpec initialiser from the raw oracle args."""
    return (
        '  {{ {id}, {icon}, {name}, {label}, {menu}, {tooltip}, {type},\n'
        '    action_callback_{cid}, &action_{cid} }},'
    ).format(
        id=_c_expr(entry["raw_id"]),
        icon=_c_expr(entry["raw_icon"]),
        name=_c_expr(entry["raw_name"]),
        label=_c_expr(entry["raw_label"]),
        menu=_c_expr(entry["raw_menu_label"]),
        tooltip=_c_expr(entry["raw_tooltip"]),
        type=entry["raw_type"],
        cid=entry["cid"],
    )


def _sections(entries):
    """Group entries by oracle section, preserving first-seen order."""
    order = []
    groups = {}
    for entry in entries:
        key = entry["section"]
        if key not in groups:
            groups[key] = {"title": entry["section_title"], "entries": []}
            order.append(key)
        groups[key]["entries"].append(entry)
    return [(groups[key]["title"], groups[key]["entries"]) for key in order]


def render_header(entries):
    """Render the complete ``actions.h`` text."""
    lines = [LICENSE_HEADER, H_HEADER_NOTE]

    for title, members in _sections(entries):
        lines.append(f"\n/* {title} */\n")
        for entry in members:
            lines.append(f"extern GschemAction *action_{entry['cid']};")
        lines.append("")
        for entry in members:
            lines.append(
                "void action_callback_{cid} (GschemAction *action,\n"
                "{pad}GschemToplevel *w_current);".format(
                    cid=entry["cid"],
                    pad=" " * (len("void action_callback_") + len(entry["cid"]) + 1)))

    lines.append("""
/*! \\brief Register every C-defined gschem action.
 *
 * Called once during startup, after the action smob type is created and
 * before any palette is built, so that each action exists by the time the
 * menus ask for it.
 */
void gschem_register_all_actions (void);
""")
    lines.append("\nG_END_DECLS\n\n#endif /* GSCHEM_ACTIONS_H */\n")
    return "\n".join(lines)


def render_source(entries):
    """Render the complete ``actions.c`` text.

    Returns (source_text, {cid: [change descriptions]}) so the caller can
    journal every deviation from the oracle instead of hiding it.
    """
    lines = [LICENSE_HEADER, C_HEADER_NOTE]
    rewrites = {}

    lines.append(""
                 "\n/* Storage for the global action pointers.  These are the handles\n"
                 " * other C files use to change an action's sensitivity or checked\n"
                 " * state; they are filled in by gschem_register_all_actions(). */\n")
    for entry in entries:
        lines.append(f"GschemAction *action_{entry['cid']} = NULL;")

    lines.append(""
                 "\nstatic const GschemActionSpec action_specs[] = {")
    for title, members in _sections(entries):
        lines.append(f"\n  /* {title} */")
        for entry in members:
            lines.append(_spec_row(entry))
    lines.append("};\n")

    lines.append("""
/*! \\brief Register every C-defined gschem action.
 *
 * Walks ::action_specs, registering each action and storing the resulting
 * object in the matching ``action_<cid>`` global so that other C files can
 * change its sensitivity or checked state.
 */
void
gschem_register_all_actions (void)
{
  for (gsize i = 0; i < G_N_ELEMENTS (action_specs); i++) {
    const GschemActionSpec *spec = &action_specs[i];
    GschemAction *action = gschem_action_register (spec->id,
                                                   spec->icon_name,
                                                   _(spec->name),
                                                   _(spec->label),
                                                   _(spec->menu_label),
                                                   spec->tooltip,
                                                   spec->type,
                                                   spec->activate);
    *spec->action = action;
  }
}
""")

    lines.append("\n/*! \\section callback-functions Callback Functions */\n")
    for entry in entries:
        body, changes = rewrite_body(entry["body"])
        if changes:
            rewrites[entry["cid"]] = changes
        if not body.strip():
            body = "  /* no-op */"
        if entry["comment"]:
            lines.append(f"\n{entry['comment']}\n")
        lines.append(
            "\nvoid\naction_callback_{cid} (GschemAction *action,\n"
            "{pad}GschemToplevel *w_current)\n{{\n{body}\n}}\n".format(
                cid=entry["cid"],
                pad=" " * (len("action_callback_") + len(entry["cid"]) + 1),
                body=body))

    return "\n".join(lines), rewrites

#!/bin/sh
# gEDA environment for running gschem/gattrib/gaf from this source tree.
#
# Source this file; do not execute it:
#
#     . ./gattrib_env.sh
#
# Why this is needed: libgeda finds its Scheme code, component library and
# menus through GEDADATA (see s_path_sys_data() in libgeda/src/s_basic.c).
# When GEDADATA is unset libgeda falls back to the path baked in at configure
# time, which for a default uninstalled build is /usr/local/share/geda.  That
# path does not exist on most machines, so gattrib starts but refuses every
# schematic with "No components found in entire design!" because no
# component library is registered.
#
# Set GEDA_PREFIX to the prefix of an installed gEDA (the directory
# containing share/<release-directory>).  Anything already in the environment wins, so a
# caller can override any single variable.

if [ -n "${BASH_SOURCE:-}" ]; then
  _geda_self="${BASH_SOURCE}"
else
  _geda_self="$0"
fi
GEDA_TREE=$(cd "$(dirname "$_geda_self")" && pwd)
export GEDA_TREE
unset _geda_self

# Read the release directory generated by configure; do not mix releases.
GEDA_PACKAGE_DIR=$(sed -n 's/^GEDA_PACKAGE_DIR = //p' "$GEDA_TREE/Makefile")
if [ -z "$GEDA_PACKAGE_DIR" ]; then
  echo "gattrib_env.sh: configure this source tree first" >&2
  return 1 2>/dev/null || exit 1
fi
if [ -n "${GEDA_PREFIX:-}" ]; then
  GEDA_DATA_PATH="$GEDA_PREFIX/share/$GEDA_PACKAGE_DIR"
  GEDA_RC_PATH="$GEDA_DATA_PATH"
else
  GEDA_DATA_PATH=$(sed -n 's/^#define GEDADATADIR "\(.*\)"/\1/p' "$GEDA_TREE/config.h")
  GEDA_RC_PATH=$(sed -n 's/^#define GEDARCDIR "\(.*\)"/\1/p' "$GEDA_TREE/config.h")
fi
if [ ! -d "$GEDA_DATA_PATH/sym" ]; then
  echo "gattrib_env.sh: no component library at $GEDA_DATA_PATH/sym" >&2
  echo "  set GEDA_PREFIX to the prefix holding share/$GEDA_PACKAGE_DIR/sym, then re-source." >&2
  return 1 2>/dev/null || exit 1
fi

# System data: gafrc.d (component library list), bitmaps, menus, gattrib's
# menus XML.  libgeda reads this through s_path_sys_data().
export GEDADATA="$GEDA_DATA_PATH"

# System configuration: where system-gafrc lives.
export GEDADATARC="$GEDA_RC_PATH"

# Let the uninstalled binaries in this tree be found without installing.
case ":$PATH:" in
  *":$GEDA_TREE/gattrib/src:"*) ;;
  *) PATH="$GEDA_TREE/gattrib/src:$GEDA_TREE/gschem/src:$GEDA_TREE/gaf:$PATH"; export PATH ;;
esac

# Octopart/Nexar credentials for the BOM hooks (see gattrib_bom.h).  Leave
# these unset unless you have an account; the offline supplier needs neither.
#   export GATTRIB_NEXAR_CLIENT_ID=...
#   export GATTRIB_NEXAR_CLIENT_SECRET=...
# Set GATTRIB_BOM_OFFLINE=1 to force the built-in supplier table.
: "${GATTRIB_BOM_CURRENCY:=USD}"
: "${GATTRIB_BOM_COUNTRY:=US}"
export GATTRIB_BOM_CURRENCY GATTRIB_BOM_COUNTRY

# Diagnostics: set to any value to print the loaded component, net and pin
# tables to stderr on startup (see x_window_debug_dump_sheet() in x_window.c).
#   GATTRIB_DEBUG_DUMP=1 gattrib design.sch
#
# Note: gattrib reads its menu definition from $GEDADATA/gattrib-menus.xml.
# After editing gattrib/lib/gattrib-menus.xml in this tree, copy it there
# (or run "make install" in gattrib/lib), otherwise new menu items such as
# Edit->Fetch BOM data will not appear.

if [ -n "${GATTRIB_NEXAR_CLIENT_ID:-}" ] && [ -n "${GATTRIB_NEXAR_CLIENT_SECRET:-}" ]; then
  echo "gEDA tree: $GEDA_TREE"
  echo "GEDADATA:  $GEDADATA (Octopart/Nexar credentials present)"
else
  echo "gEDA tree: $GEDA_TREE"
  echo "GEDADATA:  $GEDADATA (no Nexar credentials; BOM lookups use the offline supplier)"
fi
